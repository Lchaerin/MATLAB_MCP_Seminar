%[text] | --- | --- |
%[text] | **NIR 분광법** | 근적외선(약 780–2500 nm)을 시료에 비춰 파장별 흡수 정도를 재는 측정법. 시료 손상 없이 빠르게 성분을 추정할 때 쓰임 |
%[text] | **옥탄가** | 휘발유가 엔진 안에서 비정상 연소(노킹)를 견디는 정도를 나타내는 품질 지표. 이 실습에서 맞히려는 값 |
%[text] | **X와 y** | X는 입력(예측 변수, 여기서는 스펙트럼), y는 맞히려는 값(반응 변수, 여기서는 옥탄가) |
%[text:table]
%[text] **분석 방법**
%[text:table]{"columnWidths":[190,600]}
%[text] | 용어 | 한 줄 설명 |
%[text] | --- | --- |
%[text] | **다중공선성** | 이웃한 파장끼리 값이 거의 같이 움직여 일반 회귀가 불안정해지는 문제. 아래 방법들이 필요한 이유 |
%[text] | **PCA (주성분 분석)** | 수백 개 변수를 정보 손실이 가장 적도록 몇 개의 새 축(주성분)으로 요약하는 방법 |
%[text] | **PCR (주성분 회귀)** | PCA로 요약한 주성분으로 회귀하는 방법. 요약할 때 y는 보지 않음 |
%[text] | **PLS 회귀 (부분 최소제곱)** | y와 관련이 큰 방향부터 성분을 뽑아 회귀하는 방법. 분광 데이터 분석의 대표 기법 |
%[text] | **성분 수** | PCA·PLS에서 사용할 요약 축의 개수. 너무 적으면 정보가 부족하고, 너무 많으면 과적합 |
%[text:table]
%[text] **평가**
%[text:table]{"columnWidths":[190,600]}
%[text] | 용어 | 한 줄 설명 |
%[text] | --- | --- |
%[text] | **과적합** | 학습에 쓴 데이터에만 지나치게 맞춰져 새 데이터에서는 성능이 떨어지는 현상 |
%[text] | **훈련/평가 분리** | 모델을 만드는 데이터(훈련 세트)와 성능을 재는 데이터(평가 세트)를 미리 나누는 것 |
%[text] | **교차검증 (k-fold)** | 데이터를 k묶음으로 나눠 한 묶음씩 돌아가며 평가에 쓰고 결 | 평균 내는 방법 |
%[text] | **RMSE** | 예측 오차의 평균적인 크기. 단위는 y와 같고(여기서는 옥탄가), 작을수록 좋음. 평가 세트에서 재면 RMSEP, 교차검증으로 재면 RMSECV |
%[text] | **결정계수** $R^2$ | 모델이 y의 변동을 얼마나 설명하는지 나타내는 값. 1에 가까울수록 잘 설명 |
